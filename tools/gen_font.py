#!/usr/bin/env python3
"""Rasterize the UI fonts into a C header (8-bit alpha atlases).
Fonts: JetBrains Mono (OFL 1.1) with DejaVu Sans (Bitstream Vera license) for symbols -
licenses are shipped in port/echofield/licenses. Debian: fonts-jetbrains-mono fonts-dejavu-core.
Run: python3 tools/gen_font.py > src/font_data.h
"""
import sys
from PIL import Image, ImageDraw, ImageFont

DV = "/usr/share/fonts/truetype/dejavu/"
JB = "/usr/share/fonts/truetype/jetbrains-mono/JetBrainsMono-"
FONTS = [  # name, file, px  (order = F_SMALL, F_BODY, F_BIG, F_LOGO, F_TINY)
    ("small", JB + "Medium.ttf", 13),
    ("body", JB + "SemiBold.ttf", 16),
    ("big", JB + "Light.ttf", 34),
    ("logo", JB + "ExtraBold.ttf", 15),
    ("tiny", JB + "Medium.ttf", 11),
]
SPECIAL = {1: "▶", 2: "◀", 3: "●", 4: "◆", 5: "✓", 6: "✗",
           7: "▲", 8: "▼", 11: "○", 12: "♪", 14: "…", 15: "↺", 16: "·", 17: "↕", 18: "↔"}
codes = list(range(32, 127)) + sorted(SPECIAL)

out = ["/* generated by tools/gen_font.py - do not edit */", "#ifndef EF_FONT_DATA_H", "#define EF_FONT_DATA_H",
       "#include <stdint.h>",
       "typedef struct { int16_t x, y, w, h, xoff, yoff, adv; } EfGlyph;",
       "typedef struct { int height, ascent, atlas_w, atlas_h; const EfGlyph *glyphs; const uint8_t *atlas; } EfFontData;"]
for name, path, px in FONTS:
    font = ImageFont.truetype(path, px)
    fallback = ImageFont.truetype(DV + "DejaVuSans-Bold.ttf", px)
    ascent, descent = font.getmetrics()
    height = ascent + descent
    glyphs = {}
    W = 512
    x = y = 0
    rowh = 0
    tiles = []
    for c in codes:
        ch = SPECIAL.get(c, chr(c))
        f = font
        if c in SPECIAL and font.getbbox(ch) == (0, 0, 0, 0):
            f = fallback
        try:
            bbox = f.getbbox(ch)
        except Exception:
            bbox = (0, 0, 0, 0)
        adv = int(round(f.getlength(ch)))
        if c >= 32:
            adv = int(round(font.getlength("M")))  # monospace advance
        w = max(0, bbox[2] - bbox[0]); h = max(0, bbox[3] - bbox[1])
        img = Image.new("L", (w + 2, h + 2), 0)
        if w and h:
            ImageDraw.Draw(img).text((1 - bbox[0], 1 - bbox[1]), ch, font=f, fill=255)
        w += 2; h += 2
        if x + w > W:
            x = 0; y += rowh; rowh = 0
        tiles.append((c, x, y, img))
        glyphs[c] = (x, y, w, h, bbox[0] - 1, bbox[1] - 1, adv)
        x += w; rowh = max(rowh, h)
    H = y + rowh
    atlas = Image.new("L", (W, H), 0)
    for c, tx, ty, img in tiles:
        atlas.paste(img, (tx, ty))
    data = atlas.tobytes()
    out.append("static const EfGlyph k_glyph_%s[128] = {" % name)
    for c in range(128):
        g = glyphs.get(c, (0, 0, 0, 0, 0, 0, 0))
        out.append("  {%d,%d,%d,%d,%d,%d,%d}," % g)
    out.append("};")
    out.append("static const uint8_t k_atlas_%s[%d] = {" % (name, len(data)))
    for i in range(0, len(data), 40):
        out.append("  " + ",".join(str(b) for b in data[i:i + 40]) + ",")
    out.append("};")
    out.append("static const EfFontData k_font_%s = {%d, %d, %d, %d, k_glyph_%s, k_atlas_%s};" % (name, height, ascent, W, H, name, name))
out.append("#endif")
sys.stdout.write("\n".join(out) + "\n")
